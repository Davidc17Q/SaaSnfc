/**
 * Devuelve el markup SVG de un icono.
 * @param {string} name  Nombre del icono (clave de ICON_PATHS).
 * @param {object} opts  { size = 18, cls = '', stroke = 2 }
 */
function icon(name, opts = {}) {
  const paths = ICON_PATHS[name];
  if (!paths) return '';
  const size = opts.size || 18;
  const cls = opts.cls ? ` ${opts.cls}` : '';
  const stroke = opts.stroke || 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" class="icon${cls}" aria-hidden="true">${paths}</svg>`;
}

// Exponer global para uso en app.js e inline en HTML.
window.icon = icon;

/**
 * Rellena todos los elementos con [data-icon] con su SVG correspondiente.
 * Respeta un tamaño opcional vía [data-icon-size].
 */
function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const name = el.getAttribute('data-icon');
    const size = parseInt(el.getAttribute('data-icon-size') || '18', 10);
    el.innerHTML = icon(name, { size });
  });
}
window.hydrateIcons = hydrateIcons;

document.addEventListener('DOMContentLoaded', () => hydrateIcons());
